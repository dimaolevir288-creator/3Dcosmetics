package ru.hat1.cosmetics.config

import org.bukkit.plugin.java.JavaPlugin
import java.io.File
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

/**
 * Генерирует `info.txt` рядом с `config.yml`.
 *
 * Файл пересоздаётся при каждом включении плагина и содержит полное описание
 * плагина: версию, команды, права, формат конфигов и инструкцию по косметике.
 */
class InfoFileWriter(private val plugin: JavaPlugin) {

    private val file: File get() = File(plugin.dataFolder, FILE_NAME)

    /** Записывает `info.txt`, возвращая созданный файл. */
    fun write(): File {
        plugin.dataFolder.mkdirs()
        file.writeText(buildText(), Charsets.UTF_8)
        return file
    }

    private fun buildText(): String = buildString {
        val stamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("dd.MM.yyyy HH:mm:ss"))

        appendLine("=".repeat(72))
        appendLine("  3DCosmetics — 3D-косметика для Paper")
        appendLine("=".repeat(72))
        appendLine()
        appendLine("Версия плагина : ${plugin.description.version}")
        appendLine("API версия     : ${plugin.description.apiVersion ?: "неизвестно"}")
        appendLine("Автор          : ${plugin.description.authors.joinToString(", ").ifEmpty { "hat1" }}")
        appendLine("Сервер         : ${plugin.server.name} ${plugin.server.version}")
        appendLine("Файл создан    : $stamp")
        appendLine("Папка плагина  : ${plugin.dataFolder.absolutePath}")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  КОМАНДЫ")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("/cosmetics                      Открыть меню косметики")
        appendLine("/cosmetics give <игрок> <id>    Выдать косметику игроку")
        appendLine("/cosmetics take <игрок> <id>    Забрать косметику у игрока")
        appendLine("/cosmetics off                  Снять всю косметику с себя")
        appendLine("/cosmetics trial <id>           Примерить косметику на несколько секунд")
        appendLine("/cosmetics reload               Перезагрузить конфиги и ресурспак")
        appendLine("/cosmetics import [force]       Импортировать .bbmodel из blockbench/")
        appendLine()
        appendLine("Алиасы: /cos, /hat, /hats")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ПРАВА (PERMISSIONS)")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("cosmetics.use      По умолчанию: все. Открытие меню и /cosmetics off")
        appendLine("cosmetics.admin    По умолчанию: оператор. Команды give / take / reload")
        appendLine()
        appendLine("Права на отдельные предметы задаются в cosmetics.yml в поле permission.")
        appendLine("Пример: cosmetics.hat.crown")
        appendLine()
        appendLine("Выдача права через LuckPerms:")
        appendLine("  /lp user <ник> permission set cosmetics.hat.crown")
        appendLine("Забрать право:")
        appendLine("  /lp user <ник> permission unset cosmetics.hat.crown")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ЭКОНОМИКА")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("Валюта берётся из Vault. Нужны установленные Vault и плагин экономики")
        appendLine("(EssentialsX, CMI, Craftconomy и т.п.).")
        appendLine("Если Vault не найден, меню работает, но кнопка покупки сообщает об ошибке.")
        appendLine("Символ валюты в меню задаётся в config.yml: economy.currency-symbol")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ФАЙЛЫ ПЛАГИНА")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("config.yml          Основные настройки: меню, звуки, сообщения")
        appendLine("cosmetics.yml       Список категорий и предметов косметики")
        appendLine("info.txt            Этот файл")
        appendLine("blockbench/         Папка для готовых моделей Blockbench (.bbmodel)")
        appendLine("resourcepack/       Исходники ресурспака (распаковываются при старте)")
        appendLine("3DCosmetics.zip   Готовый архив ресурспака для игроков")
        appendLine("players/<uuid>.yml  Данные игроков: что куплено и что надето")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  РЕСУРСПАК")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("При первом запуске плагин распаковывает ресурспак в папку resourcepack/")
        appendLine("и собирает из неё архив 3DCosmetics.zip в папке плагина.")
        appendLine()
        appendLine("Чтобы игроки видели 3D-модели, архив нужно раздавать по HTTP:")
        appendLine("  1. Загрузите 3DCosmetics.zip на любой файлхостинг с прямым ссылкой")
        appendLine("     (или поднимите свой веб-сервер, например nginx).")
        appendLine("  2. Пропишите полученную ссылку в config.yml:")
        appendLine("       resource-pack:")
        appendLine("         url: \"https://ваш-хостинг/3DCosmetics.zip\"")
        appendLine("         force: true     # клиент не сможет отказаться от загрузки")
        appendLine("  3. Выполните /cosmetics reload либо перезапустите сервер.")
        appendLine()
        appendLine("Если изменить модели или текстуры в папке resourcepack/, удалите")
        appendLine("3DCosmetics.zip и перезапустите сервер — архив соберётся заново.")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  МОДЕЛИ ИЗ BLOCKBENCH")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("Плагин сам пересобирает модели Blockbench в формат ресурспака:")
        appendLine()
        appendLine("1. Сделайте модель в Blockbench (формат Java Item или CPM).")
        appendLine("2. ВАЖНО: при сохранении включите встраивание текстур")
        appendLine("   (File → Save, галочка \"Embed Textures\"), иначе текстуры")
        appendLine("   придётся класть рядом отдельными PNG-файлами.")
        appendLine("3. Положите файл .bbmodel в папку:")
        appendLine("     plugins/3DCosmetics/blockbench/")
        appendLine("4. Выполните команду:  /cosmetics import")
        appendLine()
        appendLine("Плагин разберёт модель, сконвертирует геометрию в модель")
        appendLine("предмета Minecraft, запишет её в ресурспак и пересоберёт архив:")
        appendLine()
        appendLine("  assets/3DCosmetics/models/item/<имя_файла>.json")
        appendLine("  assets/3DCosmetics/textures/item/<имя_файла>.png")
        appendLine()
        appendLine("Для модели 'top_hat.bbmodel' получится ключ:")
        appendLine("  3DCosmetics:item/top_hat")
        appendLine()
        appendLine("Укажите его в cosmetics.yml:")
        appendLine()
        appendLine("   my_hat:")
        appendLine("     category: hats")
        appendLine("     model:")
        appendLine("       material: PAPER")
        appendLine("       item-model: \"3DCosmetics:item/top_hat\"")
        appendLine("       anchor: head")
        appendLine()
        appendLine("Особенности конвертации:")
        appendLine("  • Ось Y разворачивается автоматически (Y-вверх → Y-вниз).")
        appendLine("  • Модель центрируется по X/Z и ставится на макушку головы.")
        appendLine("  • Повороты костей (bones) «запекаются» в вершины геометрии.")
        appendLine("  • >1 текстуры в модели: имена файлов получат суффикс _0, _1, …")
        appendLine("  • Mesh-элементы и анимации не переносятся: в 1.21.11 модель")
        appendLine("    предмета поддерживает только кубы.")
        appendLine()
        appendLine("Пересобрать всё заново (игнорируя кеш по хешу):")
        appendLine("  /cosmetics import force")
        appendLine()
        appendLine("Импорт также запускается автоматически при старте сервера")
        appendLine("и при /cosmetics reload. После импорта пакет отправляется")
        appendLine("всем игрокам онлайн заново.")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ДОБАВЛЕНИЕ СВОЕЙ КОСМЕТИКИ")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("1. Откройте cosmetics.yml и добавьте запись в секцию cosmetics:")
        appendLine()
        appendLine("   my_item:")
        appendLine("     category: hats")
        appendLine("     display-name: \"&bМоя шляпа\"")
        appendLine("     description:")
        appendLine("       - \"&7Описание предмета\"")
        appendLine("     icon: LEATHER_HELMET")
        appendLine("     price: 1000.0")
        appendLine("     permission: \"cosmetics.hat.my_item\"")
        appendLine("     model:")
        appendLine("       material: PAPER")
        appendLine("       custom-model-data: 1005")
        appendLine("       scale: 0.9")
        appendLine("       translation: [0.0, 0.34, 0.0]")
        appendLine("       rotation: [0.0, 0.0, 0.0]")
        appendLine("       anchor: head")
        appendLine("       billboard: FIXED")
        appendLine()
        appendLine("2. Положите текстуру и модель в resourcepack/assets/3DCosmetics/.")
        appendLine("3. Выполните /cosmetics reload.")
        appendLine()
        appendLine("Доступные anchor: head, back, chest, feet, left_arm, right_arm,")
        appendLine("                   left_leg, right_leg")
        appendLine("Доступные billboard: FIXED, VERTICAL, HORIZONTAL, CENTER")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  СЛОТЫ И ЦЕНЫ")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("Каждая косметика занимает один из четырёх слотов:")
        appendLine()
        appendLine("  head — голова (шляпы, маски, рога)")
        appendLine("  body — тело  (плащи, крылья, рюкзаки)")
        appendLine("  arms — руки  (наручи, перчатки)")
        appendLine("  legs — ноги  (сапоги, наколенники)")
        appendLine()
        appendLine("В пределах одного слота носится одна вещь, разные слоты складываются.")
        appendLine("Косметика НЕ занимает слоты брони и инвентаря — она рисуется")
        appendLine("сущностями ItemDisplay, поэтому шляпа надевается поверх шлема.")
        appendLine()
        appendLine("Слот указывается в cosmetics.yml полем slot. Если его нет —")
        appendLine("слот выводится из поля anchor:")
        appendLine("  head -> head | chest, back -> body | *_arm -> arms | feet, *_leg -> legs")
        appendLine()
        appendLine("Цены по слотам задаются секцией prices:")
        appendLine()
        appendLine("  prices:")
        appendLine("    head:")
        appendLine("      default: 2500.0    # цена, если у косметики нет своего price")
        appendLine("      multiplier: 1.0    # множитель для всего слота")
        appendLine()
        appendLine("Приоритет: price у косметики -> default слота -> 0.")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ПРИМЕРКА (TRIAL)")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("Косметику можно примерить до покупки:")
        appendLine("  ПКМ по кнопке в меню или /cosmetics trial <id>")
        appendLine()
        appendLine("Предмет надевается на несколько секунд и затем снимается сам,")
        appendLine("предыдущая вещь в этом же слоте возвращается на место.")
        appendLine()
        appendLine("Каждый предмет можно примерить ТОЛЬКО ОДИН РАЗ за всё время:")
        appendLine("использованные примерки сохраняются в players/<uuid>.yml (поле trials)")
        appendLine("и не сбрасываются при перезаходе.")
        appendLine()
        appendLine("Настройки в config.yml:")
        appendLine("  trial:")
        appendLine("    enabled: true             # выключить примерки совсем")
        appendLine("    duration-seconds: 5        # длительность")
        appendLine("Для отдельной косметики примерку можно запретить полем trial: false.")
        appendLine()

        appendLine("-".repeat(72))
        appendLine("  ЧАСТЫЕ ПРОБЛЕМЫ")
        appendLine("-".repeat(72))
        appendLine()
        appendLine("Косметика видна как бумага/предмет без модели")
        appendLine("  Не загружен ресурспак. Проверьте resource-pack.url и доступность ссылки.")
        appendLine()
        appendLine("Косметика не появляется после выдачи")
        appendLine("  Проверьте, что у игрока есть право cosmetics.<категория>.<id>,")
        appendLine("  и что предмет надет в меню (куплен или выдан — не одно и то же).")
        appendLine()
        appendLine("Игрок купил, но после перезахода косметика пропала")
        appendLine("  Проверьте папку players/ и права на запись в папку плагина.")
        appendLine()
        appendLine("Своя косметика не видна / скачалась как бумага")
        appendLine("  Проверьте, что в cosmetics.yml указан item-model:")
        appendLine("  \"3DCosmetics:item/<имя>\" и что /cosmetics import выполнен.")
        appendLine()
        appendLine("В консоли: \"Blockbench: <файл> пропущен\"")
        appendLine("  Плагин не смог разобрать .bbmodel. Проверьте, что файл не повреждён")
        appendLine("  и содержит кубы (elements). Mesh-модели не поддерживаются.")
        appendLine()
        appendLine("Модель есть, но белая/без текстуры")
        appendLine("  Текстуры не были встроены при сохранении в Blockbench.")
        appendLine("  Пересохраните модель с \"Embed Textures\" или положите PNG рядом.")
        appendLine()
        appendLine("=".repeat(72))
        appendLine("  Поддержка: обратитесь к администратору сервера.")
        appendLine("=".repeat(72))
    }

    companion object {
        const val FILE_NAME = "info.txt"
    }
}
